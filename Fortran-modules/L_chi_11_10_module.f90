    function L_11_10_40(s) result(f)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f, s1, w, X, I1, I2, g(0:4), l(1:40), lambda(1:40), omega(1:40)
    real (kind=qp)                  :: M
    integer                         :: N, r, k
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_11_10_prime(s,X)
    N=floor(sqrt(11*s%im/(2*pi)))
    r=mod(N,11)
    k=(N-r)/11
    g=main_sums(s,N,13)
    M=real(N,kind=qp)+0.5
    s1=1-conjg(s)
    w=exp(-s*log(M))
    select case(r)
    case(0)
        lambda=lambda_r0; omega=omega_r0
    case(1)
        lambda=lambda_r1; omega=omega_r1
    case(2)
        lambda=lambda_r2; omega=omega_r2
    case(3)
        lambda=lambda_r3; omega=omega_r3
    case(4)
        lambda=lambda_r4; omega=omega_r4
    case(5)
        lambda=lambda_r5; omega=omega_r5
    case(6)
        lambda=-lambda_r4(40:1:-1); omega=-omega_r4(40:1:-1)
    case(7)
        lambda=-lambda_r3(40:1:-1); omega=-omega_r3(40:1:-1)
    case(8)
        lambda=-lambda_r2(40:1:-1); omega=-omega_r2(40:1:-1)
    case(9)
        lambda=-lambda_r1(40:1:-1); omega=-omega_r1(40:1:-1)
    case default
        lambda=-lambda_r0(40:1:-1); omega=-omega_r0(40:1:-1)
    end select
    l=log(1+ii*lambda/M)
    I1=sum(omega*exp(-(2*pi/11)*M*lambda-s*l))
