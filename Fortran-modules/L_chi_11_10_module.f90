    function L_11_10_prime_Euler_Maclaurin(s) result(f)
! computes f(1)=L(s,chi_{11,10}) and f(2)=L'(s,chi_{11,10}) via Euler-Maclaurin summation
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), m, m1, w, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2, v
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=11*(floor(abs(s)/5)+20)
    N2=one/N**2
    m=1
    m1=0
    f=0
    do k=1,100
        f(1)=f(1)+b(k)*m
        f(2)=f(2)+b(k)*m1
        w=(s+2*k-2)*(s+2*k-1)
        m1=(m1*w+m*(2*s+4*k-3))*N2
        m=m*w*N2
    end do
    v=log(real(N, kind=qp))
    w=exp(-s*v)
    f(1)=w*f(1)
    f(2)=-v*f(1)+w*f(2)
    g=main_sums(s,N-1,12)
    f=f+g(1:2)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_10_prime_Euler_Maclaurin
