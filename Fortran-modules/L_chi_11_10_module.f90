    function L_11_10_prime(s) result(f)
!    f=L_11_10_prime(s) computes f(1)=L(s,chi_{11,10}) and f(2)=L'(s,chi_{11,10})
!    The input s must be a scalar (this code is not vectorized)
!--------------------------------------------------------------------------
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), g(1:2), X1, X2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    if (abs(s%im)>2.6e+18_qp) then
        error stop "L_chi_11_10_module: |Im(s)| exceeds the supported limit"
    end if
    if (s%re>=0.5) then
        f=L_11_10_prime_half_plane(s)
    else ! use reflection formula for L(s,chi_{11,10}) for Re(s)<0.5
        call X_11_10_prime(s,X1,X2)
        g=L_11_10_prime_half_plane(1-s)
        f(1)=X1*g(1)
        f(2)=X2*g(1)-X1*g(2)
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_10_prime
