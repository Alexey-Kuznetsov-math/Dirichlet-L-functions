    function L_11_10(s) result(f)
!    f=L_11_10(s) computes L(s,chi_{11,10}) for complex input s
!    The input s must be a scalar (this code is not vectorized)
!--------------------------------------------------------------------------
    implicit none
    complex (kind=qp), intent(in) :: s
    complex (kind=qp)             :: f, X
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    if (abs(s%im)>2.6e+18_qp)  then
        error stop "L_chi_11_10_module: |Im(s)| exceeds the supported limit"
    end if
    if (s%re>=0.5) then
        f=L_11_10_half_plane(s)
    else ! use reflection formula for Re(s)<0.5
        call X_11_10_prime(s,X)
        f=X*L_11_10_half_plane(1-s)
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_10
!#######################################################################
    function L_11_10_half_plane(s) result(f)
! computes L(s,chi) in the half-plane Re(s)>=0.5
    implicit none
    complex (kind=qp), intent(in)  :: s
    complex (kind=qp)              :: f, g(0:4)
    real(kind=qp)                  :: N_sum, N_EM, N_40
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N_sum=exp(75/max(s%re-1,0.5_qp))*0.23 ! computational complexity of direct summation -- counting the number of evaluations of k^{-s}
    N_EM=(2.2_qp*abs(s)+220)*0.23                 ! computational complexity of L_11_10_Euler_Maclaurin function
    N_40=sqrt(11*abs(s%im)/(2*pi))*0.23+81     ! computational complexity of L_11_10_40 function
    if (abs(s%im)<400) then
        if (N_sum<N_EM) then
            g=main_sums(s,floor(N_sum/0.23),0)
            f=g(0)
        else
            f=L_11_10_Euler_Maclaurin(s)
        end if
    elseif (N_sum<N_40) then
        g=main_sums(s,floor(N_sum/0.23),0)
        f=g(0)
    else
        if (s%im>0) then
            f=L_11_10_40(s)
        else
            f=conjg(L_11_10_40(conjg(s)))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_10_half_plane
!#######################################################################
    function L_11_10_Euler_Maclaurin(s) result(f)
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f, m, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=11*(floor(abs(s)/5)+20)
    N2=one/N**2
    m=1
    f=0
    do k=1,100
        f=f+b(k)*m
        m=m*(s+2*k-2)*(s+2*k-1)*N2
    end do
    f=f*exp(-s*log(real(N, kind=qp)))
    g=main_sums(s,N-1,1)
    f=f+g(1)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_10_Euler_Maclaurin
