    complex (kind=qp)               :: l(1:40), e1(1:40), e2(1:40), w, g(0:4), lambda(1:40), omega(1:40)
    real (kind=qp)                  :: M, v
    integer                         :: N, r, k
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_11_2_prime(s,X1,X2)
    N=floor(sqrt(11*s%im/(2*pi)))
    r=mod(N,11)
    k=(N-r)/11
    g=main_sums(s,N,1234)
    M=real(N,kind=qp)+0.5
    s1=1-conjg(s)
