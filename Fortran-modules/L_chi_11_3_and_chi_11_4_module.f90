    function L_11_3_half_plane(s) result(f)
! computes L(s,chi) in the half-plane Re(s)>=0.5
    implicit none
    complex (kind=qp), intent(in)  :: s
    complex (kind=qp)              :: f, g(0:4)
    real(kind=qp)                  :: N_sum, N_EM, N_40
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N_sum=exp(75/max(s%re-1,0.5_qp))*0.23_qp     ! computational complexity of direct summation -- counting the number of evaluations of k^{-s}
    N_EM=(2.2_qp*abs(s)+220)*0.23_qp                    ! computational complexity of L_11_3_Euler_Maclaurin function
    N_40=sqrt(11*abs(s%im)/(2*pi))*0.23_qp+81     ! computational complexity of L_11_3_40 function
    if (abs(s%im)<400) then
        if (N_sum<N_EM) then
            g=main_sums(s,floor(N_sum/0.23_qp),0)
            f=g(0)
        else
            f=L_11_3_Euler_Maclaurin(s)
        end if
    elseif (N_sum<N_40) then
        g=main_sums(s,floor(N_sum/0.23_qp),0)
        f=g(0)
    else
        if (s%im>0) then
            f=L_11_3_40(s)
        else
            f=conjg(L_11_4_40(conjg(s)))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_3_half_plane
