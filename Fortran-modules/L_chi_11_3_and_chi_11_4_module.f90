    function L_11_3_Euler_Maclaurin(s) result(f)
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f, m, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=11*(floor(abs(s)/5)+20)
    N2=(one/real(N,kind=qp))**2
    m=s/real(N,kind=qp)
    f=0
    do k=1,100
        f=f+b(k)*m
        m=m*(s+2*k-1)*(s+2*k)*N2
    end do
    f=f*exp(-s*log(real(N, kind=qp)))
    g=main_sums(s,N-1,1)
    f=f+g(1)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_3_Euler_Maclaurin
