module L_chi_11_3_and_chi_11_4_module
! provides functions for computing the Dirichlet L-function L(s,chi_{11,3}) and its derivative L'(s,chi_{11,3}),
! as well as L(s,chi_{11,4}) and its derivative L'(s,chi_{11,4})
