!    f=L_11_3(s) computes L(s,chi_{11,3}) for complex input s
!    The input s must be a scalar (this code is not vectorized)
!--------------------------------------------------------------------------
    implicit none
    complex (kind=qp), intent(in) :: s
    complex (kind=qp)             :: f, X
