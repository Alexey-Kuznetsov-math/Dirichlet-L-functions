    w=exp(-s*v)
    select case(r)
    case(0)
        lambda=lambda119_r0; omega=omega119_r0
    case(1)
        lambda=lambda119_r1; omega=omega119_r1
    case(2)
        lambda=lambda119_r2; omega=omega119_r2
    case(3)
