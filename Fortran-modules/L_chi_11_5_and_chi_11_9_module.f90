    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_9_prime_half_plane
!#######################################################################
    function L_11_5_prime_Euler_Maclaurin(s) result(f)
! computes f(1)=L(s,chi_{11,5}) and f(2)=L'(s,chi_{11,5}) via Euler-Maclaurin summation
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), m, m1, w, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2, v
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=11*(floor(abs(s)/5)+20)
    N2=(one/real(N,kind=qp))**2
    m=s/real(N,kind=qp)
    m1=one/real(N,kind=qp)
    f=0
    do k=1,100
        f(1)=f(1)+b(k)*m
        f(2)=f(2)+b(k)*m1
        w=(s+2*k-1)*(s+2*k)
        m1=(m1*w+m*(2*s+4*k-1))*N2
        m=m*w*N2
    end do
    v=log(real(N, kind=qp))
    w=exp(-s*v)
    f(1)=w*f(1)
    f(2)=-v*f(1)+w*f(2)
    g=main_sums(s,N-1,12)
    f=f+g(1:2)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_5_prime_Euler_Maclaurin
!#######################################################################
    function L_11_9_prime_Euler_Maclaurin(s) result(f)
! computes f(1)=L(s,chi_{11,9}) and f(2)=L'(s,chi_{11,9}) via Euler-Maclaurin summation
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), m, m1, w, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2, v
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=11*(floor(abs(s)/5)+20)
    N2=(one/real(N,kind=qp))**2
    m=s/real(N,kind=qp)
    m1=one/real(N,kind=qp)
    f=0
    do k=1,100
        f(1)=f(1)+conjg(b(k))*m
        f(2)=f(2)+conjg(b(k))*m1
        w=(s+2*k-1)*(s+2*k)
        m1=(m1*w+m*(2*s+4*k-1))*N2
        m=m*w*N2
    end do
    v=log(real(N, kind=qp))
    w=exp(-s*v)
    f(1)=w*f(1)
    f(2)=-v*f(1)+w*f(2)
    g=conjg(main_sums(conjg(s),N-1,12))
    f=f+g(1:2)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_9_prime_Euler_Maclaurin
!#######################################################################
    function L_11_5_prime_40(s) result(f)
! computes the 40-node quadrature approximations to L(s,chi_{11,5}) and L'(s,chi_{11,5})
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), s1, X1, X2, I1, I2, I1_prime, I2_prime
    complex (kind=qp)               :: l(1:40), e1(1:40), e2(1:40), w, g(0:4), lambda(1:40), omega(1:40)
    real (kind=qp)                  :: M, v
    integer                         :: N, r, k
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_11_5_prime(s,X1,X2)
    N=floor(sqrt(11*s%im/(2*pi)))
    r=mod(N,11)
    k=(N-r)/11
    g=main_sums(s,N,1234)
    M=real(N,kind=qp)+0.5
    s1=1-conjg(s)
    v=log(M)
    w=exp(-s*v)
    select case(r)
    case(0)
        lambda=lambda115_r0; omega=omega115_r0
    case(1)
        lambda=lambda115_r1; omega=omega115_r1
    case(2)
        lambda=lambda115_r2; omega=omega115_r2
    case(3)
        lambda=lambda115_r3; omega=omega115_r3
    case(4)
        lambda=lambda115_r4; omega=omega115_r4
    case(5)
        lambda=lambda115_r5; omega=omega115_r5
    case(6)
        lambda=-lambda115_r4(40:1:-1); omega=omega115_r4(40:1:-1)
    case(7)
        lambda=-lambda115_r3(40:1:-1); omega=omega115_r3(40:1:-1)
    case(8)
        lambda=-lambda115_r2(40:1:-1); omega=omega115_r2(40:1:-1)
    case(9)
        lambda=-lambda115_r1(40:1:-1); omega=omega115_r1(40:1:-1)
    case(10)
        lambda=-lambda115_r0(40:1:-1); omega=omega115_r0(40:1:-1)
    end select
    l=log(1+ii*lambda/M)
    e1=omega*exp(-(2*pi/11)*M*lambda-s*l)
    e2=omega*exp(-(2*pi/11)*M*lambda-s1*l)
    I1=w*sum(e1)
    I1_prime=-v*I1-w*sum(l*e1)
    I2=conjg(sum(e2))/(M*w)
    I2_prime=v*I2+conjg(sum(l*e2))/(M*w)
    f(1)=g(1)+X1*g(3)-(-1)**k*(I1+X1*I2)
    f(2)=g(2)+X2*g(3)+X1*g(4)-(-1)**k*(I1_prime+X2*I2+X1*I2_prime)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_5_prime_40
