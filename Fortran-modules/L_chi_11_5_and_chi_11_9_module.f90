    f=g(1)+X*g(3)-(-1)**k*(w*I1+X*conjg(I2)/(M*w))
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_9_40
!#######################################################################
    function L_11_5_prime(s) result(f)
!    f=L_11_5_prime(s) computes f(1)=L(s,chi_{11,5}) and f(2)=L'(s,chi_{11,5})
!    The input s must be a scalar (this code is not vectorized)
!--------------------------------------------------------------------------
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), g(1:2), X1, X2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    if (abs(s%im)>2.6e+18_qp) then
        error stop "L_chi_11_5_and_chi_11_9_module: |Im(s)| exceeds the supported limit"
    end if
    if (s%re>=0.5) then
        f=L_11_5_prime_half_plane(s)
    else ! use reflection formula for L(s,chi_{11,5}) for Re(s)<0.5
        call X_11_5_prime(s,X1,X2)
        g=L_11_9_prime_half_plane(1-s)
        f(1)=X1*g(1)
        f(2)=X2*g(1)-X1*g(2)
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_5_prime
!#######################################################################
    function L_11_9_prime(s) result(f)
!    f=L_11_9_prime(s) computes f(1)=L(s,chi_{11,9}) and f(2)=L'(s,chi_{11,9})
!    The input s must be a scalar (this code is not vectorized)
!--------------------------------------------------------------------------
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), g(1:2), X1, X2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    if (abs(s%im)>2.6e+18_qp)  then
        error stop "L_chi_11_5_and_chi_11_9_module: |Im(s)| exceeds the supported limit"
    end if
    if (s%re>=0.5) then
        f=L_11_9_prime_half_plane(s)
    else ! use reflection formula for L(s,chi_{11,9}) for Re(s)<0.5
        call X_11_5_prime(conjg(s),X1,X2)
        X1=conjg(X1); X2=conjg(X2)
        g=L_11_5_prime_half_plane(1-s)
        f(1)=X1*g(1)
        f(2)=X2*g(1)-X1*g(2)
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_9_prime
!#######################################################################
    function L_11_5_prime_half_plane(s) result(f)
! computes f(1)=L(s,chi_{11,5}) and f(2)=L'(s,chi_{11,5}) in Re(s)>=0.5
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), g(0:4)
    real(kind=qp)                   :: N_sum, N_EM, N_40
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N_sum=exp(75/max(s%re-1,0.5_qp))*0.23_qp ! computational complexity of direct summation
    N_EM=(2.2_qp*abs(s)+220)*0.23_qp               ! computational complexity of L_11_5_prime_Euler_Maclaurin
    N_40=sqrt(11*abs(s%im)/(2*pi))*0.23_qp+81 ! computational complexity of L_11_5_prime_40
    if (abs(s%im)<400) then
        if (N_sum<N_EM) then
            g=main_sums(s,floor(N_sum/0.23_qp),12)
            f=g(1:2)
        else
            f=L_11_5_prime_Euler_Maclaurin(s)
        end if
    elseif (N_sum<N_40) then
        g=main_sums(s,floor(N_sum/0.23_qp),12)
        f=g(1:2)
    else
        if (s%im>0) then
            f=L_11_5_prime_40(s)
        else
            f=conjg(L_11_9_prime_40(conjg(s)))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_11_5_prime_half_plane
!#######################################################################
    function L_11_9_prime_half_plane(s) result(f)
! computes f(1)=L(s,chi_{11,9}) and f(2)=L'(s,chi_{11,9}) in Re(s)>=0.5
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), g(0:4)
    real(kind=qp)                   :: N_sum, N_EM, N_40
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N_sum=exp(75/max(s%re-1,0.5_qp))*0.23_qp ! computational complexity of direct summation
    N_EM=(2.2_qp*abs(s)+220)*0.23_qp               ! computational complexity of L_11_9_prime_Euler_Maclaurin
    N_40=sqrt(11*abs(s%im)/(2*pi))*0.23_qp+81 ! computational complexity of L_11_9_prime_40
    if (abs(s%im)<400) then
