    subroutine X_13_5_prime(s,X1,X2)
! computes X1=X(s) and, if requested, X2=X'(s), where L(s,chi_{13,5})=X(s)*L(1-s,chi_{13,8})
! X(s)=(tau/(ii*pi))*(2*pi/13)**s*cos(pi*s/2)*Gamma(1-s).
! Called only for Re(s)<0.5, or for Re(s)>=0.5 with |Im(s)|>=400.
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)            :: s
    complex (kind=qp), intent(out)           :: X1
    complex (kind=qp), intent(out), optional :: X2
    complex (kind=qp)                        :: w, v, z
    real(kind=qp)                           :: d, r
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    d=sign(one,s%im)
    if (s%re>=0.5) then ! use X(s)=tau*(2*pi/13)**s/(2*ii*sin(pi*s/2)*Gamma(s))
        w=0
        if (abs(s%im)<26) w=exp(d*pi*ii*s)
        X1=-d*tau*exp(s*ln2pi13+0.5*d*pi*ii*s-ln_gamma_half_plane(s))/(1-w)
        if (present(X2)) then
            X2=X1*(ln2pi13+0.5*d*pi*ii*(1+w)/(1-w)-psi_half_plane(s))
        end if
    elseif (abs(s%im)<26) then ! reduce the argument near the trivial zeros s=-1,-3,-5,...
        r=anint((s%re+1)/2)
        z=s-(2*r-1)
        v=(1-2*modulo(r,2.0_qp))*(-ii*tau)*exp(s*ln2pi13+ln_gamma_half_plane(1-s))/pi
        X1=v*sin(pi*z/2)
        if (present(X2)) then
            X2=X1*(ln2pi13-psi_half_plane(1-s))+(pi/2)*v*cos(pi*z/2)
        end if
    else ! use the scaled reflection factor when |Im(s)| is large
        X1=-ii*tau*0.5*exp(s*ln2pi13-0.5*d*pi*ii*s+ln_gamma_half_plane(1-s))/pi
        if (present(X2)) then
            X2=X1*(ln2pi13-0.5*d*pi*ii-psi_half_plane(1-s))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end subroutine X_13_5_prime
