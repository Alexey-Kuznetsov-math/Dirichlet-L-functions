    function L_5_2_40(s) result(f)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f, s1, w, X, I1, I2, g(0:4), l(1:40)
    real (kind=qp)                  :: M
    integer                         :: N, r, k
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_5_2_prime(s,X)
    N=floor(sqrt(5*s%im/(2*pi)))
    r=mod(N,5)
    k=(N-r)/5
    g=main_sums(s,N,13)
    M=real(N,kind=qp)+0.5
    s1=1-conjg(s)
    w=exp(-s*log(M))
    if (r==0) then
        l=log(1+ii*lambda52_r0/M)
        I1=sum(omega52_r0*exp(-0.4_qp*pi*M*lambda52_r0-s*l))
        I2=sum(omega52_r0*exp(-0.4_qp*pi*M*lambda52_r0-s1*l))
    elseif (r==1) then
        l=log(1+ii*lambda52_r1/M)
        I1=sum(omega52_r1*exp(-0.4_qp*pi*M*lambda52_r1-s*l))
        I2=sum(omega52_r1*exp(-0.4_qp*pi*M*lambda52_r1-s1*l))
    elseif (r==2) then
        l=log(1+ii*lambda52_r2/M)
        I1=sum(omega52_r2*exp(-0.4_qp*pi*M*lambda52_r2-s*l))
        I2=sum(omega52_r2*exp(-0.4_qp*pi*M*lambda52_r2-s1*l))
    elseif (r==3) then
        l=log(1-ii*lambda52_r1/M)
        I1=-sum(omega52_r1*exp(0.4_qp*pi*M*lambda52_r1-s*l))
        I2=-sum(omega52_r1*exp(0.4_qp*pi*M*lambda52_r1-s1*l))
    else
        l=log(1-ii*lambda52_r0/M)
        I1=-sum(omega52_r0*exp(0.4_qp*pi*M*lambda52_r0-s*l))
        I2=-sum(omega52_r0*exp(0.4_qp*pi*M*lambda52_r0-s1*l))
