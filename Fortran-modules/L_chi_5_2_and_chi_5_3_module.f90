    function L_5_2_Euler_Maclaurin(s) result(f)
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f, m, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=floor(abs(s)/5)*5+100
    N2=one/N**2
    m=1
    f=0
    do k=1,100
        f=f+b(k)*m
        m=m*(s+2*k-2)*(s+2*k-1)*N2
    end do
    f=f*exp(-s*log(real(N, kind=qp)))
    g=main_sums(s,N-1,1)
    f=f+g(1)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_5_2_Euler_Maclaurin
