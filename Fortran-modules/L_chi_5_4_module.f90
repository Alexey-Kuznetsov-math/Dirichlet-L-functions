!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_5_4_prime(s,X)
    N=floor(sqrt(5*s%im/(2*pi)))
