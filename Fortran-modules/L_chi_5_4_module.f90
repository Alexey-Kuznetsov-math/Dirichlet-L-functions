    function L_5_4(s) result(f)
!    f=L_5_4(s) computes L(s,chi_{5,4}) for complex input s
!    The input s must be a scalar (this code is not vectorized)
!--------------------------------------------------------------------------
    implicit none
    complex (kind=qp), intent(in) :: s
    complex (kind=qp)             :: f, X
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    if (abs(s%im)>5.7e+18_qp)  then
        error stop "L_chi_5_4_module: |Im(s)| exceeds the supported limit"
    end if
    if (s%re>=0.5) then
        f=L_5_4_half_plane(s)
    else ! use reflection formula for Re(s)<0.5
        call X_5_4_prime(s,X)
        f=X*L_5_4_half_plane(1-s)
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_5_4
!#######################################################################
    function L_5_4_half_plane(s) result(f)
! computes L(s,chi) in the half-plane Re(s)>=0.5
    implicit none
    complex (kind=qp), intent(in)  :: s
    complex (kind=qp)              :: f, g(0:4)
    real(kind=qp)                  :: N_sum, N_EM, N_40
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N_sum=exp(75/max(s%re-1,0.5_qp))*0.23  ! computational complexity of direct summation -- counting the number of evaluations of k^{-s}
    N_EM=(abs(s)+100)*0.23                 ! computational complexity of L_5_4_Euler_Maclaurin function
    N_40=sqrt(5*abs(s%im)/(2*pi))*0.23+81  ! computational complexity of L_5_4_40 function
    if (abs(s%im)<400) then
        if (N_sum<N_EM) then
            g=main_sums(s,floor(N_sum/0.23),0)
            f=g(0)
        else
            f=L_5_4_Euler_Maclaurin(s)
        end if
    elseif (N_sum<N_40) then
        g=main_sums(s,floor(N_sum/0.23),0)
        f=g(0)
    else
        if (s%im>0) then
            f=L_5_4_40(s)
        else
            f=conjg(L_5_4_40(conjg(s)))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_5_4_half_plane
!#######################################################################
    function L_5_4_Euler_Maclaurin(s) result(f)
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f, m, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=floor(abs(s)/5)*5+100
    N2=one/N**2
    m=s/real(N,kind=qp)
    f=0
    do k=1,100
        f=f+b(k)*m
        m=m*(s+2*k-1)*(s+2*k)*N2
    end do
    f=f*exp(-s*log(real(N, kind=qp)))
    g=main_sums(s,N-1,1)
    f=f+g(1)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_5_4_Euler_Maclaurin
!#######################################################################
    function L_5_4_40(s) result(f)
