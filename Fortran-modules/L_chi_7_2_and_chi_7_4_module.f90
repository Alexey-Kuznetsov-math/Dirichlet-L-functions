    function L_7_2_prime_40(s) result(f)
! computes the 40-node quadrature approximations to L(s,chi_{7,2}) and L'(s,chi_{7,2})
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), s1, X1, X2, I1, I2, I1_prime, I2_prime
    complex (kind=qp)               :: l(1:40), e1(1:40), e2(1:40), w, g(0:4)
    real (kind=qp)                  :: M, v
    integer                         :: N, r, k
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_7_2_prime(s,X1,X2)
    N=floor(sqrt(7*s%im/(2*pi)))
    r=mod(N,7)
    k=(N-r)/7
    g=main_sums(s,N,1234)
    M=real(N,kind=qp)+0.5
    s1=1-conjg(s)
    v=log(M)
    w=exp(-s*v)
    if (r==0) then
        l=log(1+ii*lambda72_r0/M)
        e1=omega72_r0*exp(-(2*pi/7)*M*lambda72_r0-s*l)
        e2=omega72_r0*exp(-(2*pi/7)*M*lambda72_r0-s1*l)
    elseif (r==1) then
        l=log(1+ii*lambda72_r1/M)
        e1=omega72_r1*exp(-(2*pi/7)*M*lambda72_r1-s*l)
        e2=omega72_r1*exp(-(2*pi/7)*M*lambda72_r1-s1*l)
    elseif (r==2) then
        l=log(1+ii*lambda72_r2/M)
        e1=omega72_r2*exp(-(2*pi/7)*M*lambda72_r2-s*l)
        e2=omega72_r2*exp(-(2*pi/7)*M*lambda72_r2-s1*l)
    elseif (r==3) then
        l=log(1+ii*lambda72_r3/M)
        e1=omega72_r3*exp(-(2*pi/7)*M*lambda72_r3-s*l)
        e2=omega72_r3*exp(-(2*pi/7)*M*lambda72_r3-s1*l)
    elseif (r==4) then
        l=log(1-ii*lambda72_r2/M)
        e1=omega72_r2*exp(+(2*pi/7)*M*lambda72_r2-s*l)
        e2=omega72_r2*exp(+(2*pi/7)*M*lambda72_r2-s1*l)
    elseif (r==5) then
        l=log(1-ii*lambda72_r1/M)
        e1=omega72_r1*exp(+(2*pi/7)*M*lambda72_r1-s*l)
        e2=omega72_r1*exp(+(2*pi/7)*M*lambda72_r1-s1*l)
    else
        l=log(1-ii*lambda72_r0/M)
        e1=omega72_r0*exp(+(2*pi/7)*M*lambda72_r0-s*l)
        e2=omega72_r0*exp(+(2*pi/7)*M*lambda72_r0-s1*l)
    end if
    I1=w*sum(e1)
    I1_prime=-v*I1-w*sum(l*e1)
    I2=conjg(sum(e2))/(M*w)
    I2_prime=v*I2+conjg(sum(l*e2))/(M*w)
    f(1)=g(1)+X1*g(3)-(-1)**k*(I1+X1*I2)
    f(2)=g(2)+X2*g(3)+X1*g(4)-(-1)**k*(I1_prime+X2*I2+X1*I2_prime)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_7_2_prime_40
