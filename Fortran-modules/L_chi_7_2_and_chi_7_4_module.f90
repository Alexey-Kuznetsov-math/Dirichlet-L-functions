!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    call X_7_2_prime(conjg(s),X1,X2)
    X1=conjg(X1); X2=conjg(X2)
    N=floor(sqrt(7*s%im/(2*pi)))
