module L_chi_7_2_and_chi_7_4_module
! provides functions for computing the Dirichlet L-function L(s,chi_{7,2}) and its derivative L'(s,chi_{7,2}),
! as well as L(s,chi_{7,4}) and its derivative L'(s,chi_{7,4})
