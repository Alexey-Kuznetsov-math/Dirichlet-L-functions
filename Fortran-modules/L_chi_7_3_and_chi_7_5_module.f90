module L_chi_7_3_and_chi_7_5_module
! provides functions for computing the Dirichlet L-function L(s,chi_{7,3}) and its derivative L'(s,chi_{7,3}),
! as well as L(s,chi_{7,5}) and its derivative L'(s,chi_{7,5})
