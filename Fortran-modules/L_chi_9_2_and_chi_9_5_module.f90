    else
        if (s%im>0) then
            f=L_9_2_prime_40(s)
        else
            f=conjg(L_9_5_prime_40(conjg(s)))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_9_2_prime_half_plane
!#######################################################################
    function L_9_5_prime_half_plane(s) result(f)
! computes f(1)=L(s,chi_{9,5}) and f(2)=L'(s,chi_{9,5}) in Re(s)>=0.5
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), g(0:4)
    real(kind=qp)                   :: N_sum, N_EM, N_40
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N_sum=exp(75/max(s%re-1,0.5_qp))*0.23_qp ! computational complexity of direct summation
    N_EM=(1.8_qp*abs(s)+180)*0.23_qp               ! computational complexity of L_9_5_prime_Euler_Maclaurin
    N_40=sqrt(9*abs(s%im)/(2*pi))*0.23_qp+81 ! computational complexity of L_9_5_prime_40
    if (abs(s%im)<400) then
        if (N_sum<N_EM) then
            g=conjg(main_sums(conjg(s),floor(N_sum/0.23_qp),12))
            f=g(1:2)
        else
            f=L_9_5_prime_Euler_Maclaurin(s)
        end if
    elseif (N_sum<N_40) then
        g=conjg(main_sums(conjg(s),floor(N_sum/0.23_qp),12))
        f=g(1:2)
    else
        if (s%im>0) then
            f=L_9_5_prime_40(s)
        else
            f=conjg(L_9_2_prime_40(conjg(s)))
        end if
    end if
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_9_5_prime_half_plane
!#######################################################################
    function L_9_2_prime_Euler_Maclaurin(s) result(f)
! computes f(1)=L(s,chi_{9,2}) and f(2)=L'(s,chi_{9,2}) via Euler-Maclaurin summation
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), m, m1, w, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2, v
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=9*(floor(abs(s)/5)+20)
    N2=(one/real(N,kind=qp))**2
    m=1
    m1=0
    f=0
    do k=1,100
        f(1)=f(1)+b(k)*m
        f(2)=f(2)+b(k)*m1
        w=(s+2*k-2)*(s+2*k-1)
        m1=(m1*w+m*(2*s+4*k-3))*N2
        m=m*w*N2
    end do
    v=log(real(N, kind=qp))
    w=exp(-s*v)
    f(1)=w*f(1)
    f(2)=-v*f(1)+w*f(2)
    g=main_sums(s,N-1,12)
    f=f+g(1:2)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_9_2_prime_Euler_Maclaurin
!#######################################################################
    function L_9_5_prime_Euler_Maclaurin(s) result(f)
! computes f(1)=L(s,chi_{9,5}) and f(2)=L'(s,chi_{9,5}) via Euler-Maclaurin summation
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    implicit none
    complex (kind=qp), intent(in)   :: s
    complex (kind=qp)               :: f(1:2), m, m1, w, g(0:4)
    integer                         :: k, N
    real (kind=qp)                  :: N2, v
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    N=9*(floor(abs(s)/5)+20)
    N2=(one/real(N,kind=qp))**2
    m=1
    m1=0
    f=0
    do k=1,100
        f(1)=f(1)+conjg(b(k))*m
        f(2)=f(2)+conjg(b(k))*m1
        w=(s+2*k-2)*(s+2*k-1)
        m1=(m1*w+m*(2*s+4*k-3))*N2
        m=m*w*N2
    end do
    v=log(real(N, kind=qp))
    w=exp(-s*v)
    f(1)=w*f(1)
    f(2)=-v*f(1)+w*f(2)
    g=conjg(main_sums(conjg(s),N-1,12))
    f=f+g(1:2)
!~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~
    end function L_9_5_prime_Euler_Maclaurin
