module L_chi_9_4_and_chi_9_7_module
! provides functions for computing the Dirichlet L-function L(s,chi_{9,4}) and its derivative L'(s,chi_{9,4}),
! as well as L(s,chi_{9,7}) and its derivative L'(s,chi_{9,7})
! for complex values of s (in quadruple precision)
! Here chi_{9,4} is a primitive Dirichlet character mod 9 (having values (chi(j),j=1,2,..,9)=(1,rho,0,rho**2,rho**2,0,rho,1,0))
! where rho=exp(2*pi*i/3); chi_{9,7} is its complex conjugate. 
! When restricted to |Re(s)|<20, the accuracy (the scaled error |Value_computed-Value_exact|/max(1,|Value_exact|))
! is about 10^{-31} for |Im(s)|<100,  10^{-30} for |Im(s)|<1000, 10^{-29} for |Im(s)|<10 000, etc.
